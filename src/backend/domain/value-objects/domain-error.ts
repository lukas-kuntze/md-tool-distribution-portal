/**
 * Violation of a domain rule. Messages describe the rule, never the offending input,
 * so that they can be logged without leaking user-provided data.
 */
export class DomainError extends Error {
  public readonly code: DomainErrorCode;

  public constructor(code: DomainErrorCode, message: string) {
    super(message);
    this.name = 'DomainError';
    this.code = code;
  }
}
